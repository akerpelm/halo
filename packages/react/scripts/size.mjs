import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { build, transform } from 'esbuild';

const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const gzip = (code) => gzipSync(code, { level: 9 }).length;
const kB = (bytes) => Math.round(bytes / 100) / 10;

async function measureEntry(name) {
  const result = await build({
    entryPoints: [new URL(`dist/${name}.js`, root).pathname],
    bundle: true,
    minify: true,
    write: false,
    format: 'esm',
    external: ['react', 'react-dom', 'react/jsx-runtime'],
    logLevel: 'error',
  });
  return kB(gzip(result.outputFiles[0].contents));
}

async function measureStyles() {
  const { code } = await transform(read('dist/styles.css'), { loader: 'css', minify: true });
  return kB(gzip(code));
}

const sizes = {
  method: 'Minified with esbuild, React external, gzip level 9. 1 kB = 1000 bytes.',
  toast: await measureEntry('toast'),
  drawer: await measureEntry('drawer'),
  spring: await measureEntry('spring'),
  styles: await measureStyles(),
};

const table = [
  '<!-- sizes:start -->',
  '| Entry | Min + gzip |',
  '| --- | --- |',
  `| \`halo-ui-react/toast\` | ${sizes.toast} kB (includes springs) |`,
  `| \`halo-ui-react/drawer\` | ${sizes.drawer} kB (includes springs) |`,
  `| \`halo-ui-react/spring\` | ${sizes.spring} kB |`,
  `| \`styles.css\` | ${sizes.styles} kB |`,
  '',
  `${sizes.method} Generated by \`pnpm size\`.`,
  '<!-- sizes:end -->',
].join('\n');

const json = `${JSON.stringify(sizes, null, 2)}\n`;
const readme = read('README.md');
const nextReadme = readme.replace(/<!-- sizes:start -->[\s\S]*<!-- sizes:end -->/, table);
if (nextReadme === readme && !readme.includes(table)) throw new Error('README.md is missing the sizes markers');

if (process.argv.includes('--check')) {
  const stale = [read('sizes.json') !== json && 'sizes.json', readme !== nextReadme && 'README.md'].filter(Boolean);
  if (stale.length > 0) {
    console.error(`Bundle sizes changed. Run \`pnpm --filter halo-ui-react size\` and commit ${stale.join(' and ')}.\n${json}`);
    process.exit(1);
  }
  console.log('Bundle sizes are up to date.');
} else {
  writeFileSync(new URL('sizes.json', root), json);
  writeFileSync(new URL('README.md', root), nextReadme);
  console.log(json);
}
